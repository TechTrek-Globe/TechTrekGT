import { test, describe, beforeEach } from 'node:test';
import assert from 'node:assert';
import { DatabaseSync } from 'node:sqlite';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { onRequestPost as batchImportPost } from '../functions/api/import/batch.js';
import { createToken } from '../functions/utils/auth.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const financeSchema = fs.readFileSync(path.join(__dirname, '../../finance/schema.sql'), 'utf8');
const auctionSchema = fs.readFileSync(path.join(__dirname, '../auction-schema.sql'), 'utf8');

const TEST_JWT_SECRET = 'test-jwt-secret-key-32-bytes-minimum-length-for-hmac';

function createMockD1() {
  const db = new DatabaseSync(':memory:');
  db.exec(financeSchema);
  db.exec(auctionSchema);

  return {
    _raw: db,
    prepare(sql) {
      let boundParams = [];
      return {
        bind(...params) {
          boundParams = params;
          return this;
        },
        async first() {
          const stmt = db.prepare(sql);
          return stmt.get(...boundParams) || null;
        },
        async all() {
          const stmt = db.prepare(sql);
          return { results: stmt.all(...boundParams) };
        },
        async run() {
          const stmt = db.prepare(sql);
          const info = stmt.run(...boundParams);
          return { success: true, meta: { changes: info.changes } };
        }
      };
    },
    async batch(statements) {
      const results = [];
      for (const stmt of statements) {
        results.push(await stmt.run());
      }
      return results;
    }
  };
}

describe('OPT-001: Batch Import Upsert (ON CONFLICT item_id)', () => {
  let mockDb;
  let authCookie;
  const testUserId = 'usr-batch-opt-test';
  let env;

  beforeEach(async () => {
    mockDb = createMockD1();
    env = {
      DB: mockDb,
      JWT_SECRET: TEST_JWT_SECRET
    };

    mockDb._raw.exec(`
      INSERT INTO users (id, email, password_hash, name, role, is_admin, created_at)
      VALUES ('${testUserId}', 'batch-opt@techtrekgt.test', 'hash', 'Batch Opt Tester', 'user', 0, datetime('now'));

      INSERT INTO auction_invoices (id, user_id, invoice_ref, description, base_total, created_at)
      VALUES ('inv-batch-1', '${testUserId}', 'INV-BATCH-1', 'Initial Invoice', 50, datetime('now'));

      INSERT INTO auction_items (id, user_id, invoice_id, item_name, unit_price, true_total_cost, status, created_at, updated_at)
      VALUES ('item-batch-1', '${testUserId}', 'inv-batch-1', 'Signed Jersey', 50, 50, 'Available', datetime('now'), datetime('now'));
    `);

    const token = await createToken({
      userId: testUserId,
      email: 'batch-opt@techtrekgt.test',
      role: 'user',
      is_admin: 0
    }, TEST_JWT_SECRET);
    authCookie = `auth_token=${token}`;
  });

  test('POST /api/import/batch upserts auction_sales on existing item_id without constraint collision', async () => {
    // Seed pre-existing sale for item-batch-1
    mockDb._raw.exec(`
      INSERT INTO auction_sales (
        id, user_id, item_id, sale_date, platform, gross_sale_price,
        buyer_shipping_paid, actual_shipping_cost, platform_fee_pct, platform_flat_fee,
        platform_fees_amt, payment_processing_amt, promoted_listing_fee, net_proceeds,
        true_total_cost, net_profit, roi_pct, created_at
      ) VALUES (
        'sale-orig-1', '${testUserId}', 'item-batch-1', '2026-10-01', 'eBay', 100.0,
        0, 0, 0.136, 0.40,
        14.0, 0, 0, 86.0,
        50.0, 36.0, 0.72, datetime('now')
      );
    `);

    // Import batch with a new sale payload for the same item_id (new random sale id generated by import)
    const req = new Request('https://techtrekgt.com/api/import/batch', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Cookie': authCookie
      },
      body: JSON.stringify({
        strategy: 'append',
        items: [],
        sales: [{
          item_id: 'item-batch-1',
          sale_date: '2026-10-15',
          platform: 'eBay',
          gross_sale_price: 150.0,
          true_total_cost: 50.0
        }],
        comps: []
      })
    });

    const res = await batchImportPost({ request: req, env });
    assert.strictEqual(res.status, 200, 'Re-importing sale for existing item_id must succeed via ON CONFLICT(item_id)');

    const updatedSale = mockDb._raw.prepare(
      'SELECT gross_sale_price, sale_date FROM auction_sales WHERE item_id = ?'
    ).get('item-batch-1');

    assert.strictEqual(Number(updatedSale.gross_sale_price), 150.0);
    assert.strictEqual(updatedSale.sale_date, '2026-10-15');
  });

  test('POST /api/import/batch upserts auction_comps on existing item_id without constraint collision', async () => {
    // Seed pre-existing comp for item-batch-1
    mockDb._raw.exec(`
      INSERT INTO auction_comps (
        id, item_id, user_id, comp_1, comp_2, comp_3, manual_avg, recommended_list_price, updated_at
      ) VALUES (
        'comp-orig-1', 'item-batch-1', '${testUserId}', 80.0, 85.0, 90.0, 85.0, 85.0, datetime('now')
      );
    `);

    // Import batch with updated comp payload for the same item_id
    const req = new Request('https://techtrekgt.com/api/import/batch', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Cookie': authCookie
      },
      body: JSON.stringify({
        strategy: 'append',
        items: [],
        sales: [],
        comps: [{
          item_id: 'item-batch-1',
          comp_1: 120.0,
          comp_2: 125.0,
          comp_3: 130.0,
          recommended_list_price: 125.0
        }]
      })
    });

    const res = await batchImportPost({ request: req, env });
    assert.strictEqual(res.status, 200, 'Re-importing comp for existing item_id must succeed via ON CONFLICT(item_id)');

    const updatedComp = mockDb._raw.prepare(
      'SELECT comp_1, manual_avg, recommended_list_price FROM auction_comps WHERE item_id = ?'
    ).get('item-batch-1');

    assert.strictEqual(Number(updatedComp.comp_1), 120.0);
    assert.strictEqual(Number(updatedComp.manual_avg), 125.0);
    assert.strictEqual(Number(updatedComp.recommended_list_price), 125.0);
  });
});

